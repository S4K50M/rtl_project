#!/usr/bin/env python3
"""Run ESPRESSO + ROBDD construction, exhaustively check, emit usable RTL."""
import json
import sys
from pathlib import Path
sys.path.insert(0,'/workspace/toolchain/python')
from pyeda.inter import exprvars, truthtable, espresso_tts, expr2bdd


def route(v):
    x=v&3; y=(v>>2)&3; dx=(v>>4)&3; dy=(v>>6)&3
    p=1 if dx>x else 2 if dx<x else 3 if dy>y else 4 if dy<y else 0
    return 1<<p


def arbiter(v):
    req=v&31; priority=(v>>5)&7
    if priority>=5: return 0
    for k in range(5):
        i=(priority+k)%5
        if req&(1<<i): return 1<<i
    return 0


def verilog(ast,ids):
    op,*args=ast
    if op=='const': return "1'b1" if args[0] else "1'b0"
    if op=='lit':
        n=args[0]; return ('~' if n<0 else '')+f'v[{ids[abs(n)]}]'
    if op in ('or','and'):
        return '('+(' | ' if op=='or' else ' & ').join(verilog(a,ids) for a in args)+')'
    raise ValueError(ast)


def optimize(name,fn):
    v=exprvars('v',8)
    tables=[truthtable(v,''.join(str((fn(n)>>b)&1) for n in range(256))) for b in range(5)]
    minimized=espresso_tts(*tables)
    bdds=[expr2bdd(e) for e in minimized]
    for n in range(256):
        assignment={v[i]:n>>i&1 for i in range(8)}
        actual=sum(int(e.restrict(assignment).is_one())<<b for b,e in enumerate(minimized))
        assert actual==fn(n),(name,n,actual,fn(n))
        # Check reduced BDD truth values independently of ESPRESSO's expression evaluator.
        for b,bdd in enumerate(bdds):
            mapping={var:(n>>int(var.indices[0]))&1 for var in bdd.inputs}
            assert bdd.restrict(mapping).is_one()==bool(fn(n)&(1<<b))
    ids={x.uniqid:i for i,x in enumerate(v)}
    lines=[f'module {name}(input wire [7:0] v,output wire [4:0] grant);']
    for b,e in enumerate(minimized): lines.append(f'    assign grant[{b}]={verilog(e.to_ast(),ids)};')
    lines+=['endmodule','']
    return '\n'.join(lines),{'truth_rows':256,'outputs':5,'equivalent':True,
                              'espresso_cubes':sum(len(e.cover) for e in minimized),
                              'bdd_nodes_per_output':[len(list(b.dfs_postorder())) for b in bdds]}


def main():
    outputs=[]; results={}
    for name,fn in (('xy_minimized',route),('rr_minimized',arbiter)):
        rtl,results[name]=optimize(name,fn); outputs.append(rtl)
    Path('rtl/logic_minimized.sv').write_text('// Generated by scripts/logic_opt.py; all 256 rows exhaustively checked.\n'+'\n'.join(outputs))
    Path('build/logic_results.json').write_text(json.dumps(results,indent=2)+'\n')
    print(json.dumps(results,indent=2))


if __name__=='__main__': main()
